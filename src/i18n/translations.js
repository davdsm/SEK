export function translate(locale, path, vars = {}) {
  const parts = path.split('.');
  let cur = translations[locale] || translations[DEFAULT_LOCALE];
  for (const part of parts) {
    cur = cur?.[part];
  }
  if (typeof cur !== 'string') {
    cur = translations[DEFAULT_LOCALE];
    for (const part of parts) {
      cur = cur?.[part];
    }
  }
  if (typeof cur !== 'string') return path;
  return cur.replace(/\{(\w+)\}/g, (_, key) => (vars[key] != null ? String(vars[key]) : `{${key}}`));
}
